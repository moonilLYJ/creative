        st.markdown(f"**{ex['name']}**")
        st.caption(ex["desc"])

        # 검색어 키워드 생성 (예: "유소년 축구 사이드 스텝 자세")
        query = urllib.parse.quote(f"유소년 축구 {ex['name'].split('. ')[1]} 운동")
        youtube_url = f"https://www.youtube.com/results?search_query={query}"

        # 유튜브 영상 링크 버튼 추가
        st.link_button("▶️ 운동 영상 보러가기", youtube_url)


